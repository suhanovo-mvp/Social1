const F = { head: 'Cambria', body: 'Calibri' };
const MX = 0.667, W = 13.333, CW = W - MX * 2;   // 12,0 дюйма рабочей ширины
const FOOT = 'Social1 · Управление реинжинирингом и коммуникациями';

const pres = new pptxgen();
pres.layout = 'LAYOUT_WIDE';
pres.author = 'Social1';
pres.title = 'Презентация продукта Social1';
pres.subject = 'Платформа управления планированием реинжиниринга';

// ── Общие элементы ────────────────────────────────────────────────
function eyebrow(s, t, color = C.text3, y = 0.5) {
  s.addText(t.toUpperCase(), { x: MX, y, w: CW, h: 0.26, isTextBox: true, margin: 0,
    fontFace: F.body, fontSize: 11, bold: true, charSpacing: 2, color });
}
function title(s, t, { y = 0.8, size = 31, h = 0.66, w = CW } = {}) {
  s.addText(t, { x: MX, y, w, h, isTextBox: true, margin: 0, valign: 'top',
    fontFace: F.head, fontSize: size, bold: true, color: C.text, lineSpacing: size * 1.14 });
}
function lede(s, t, { y, h = 0.66, w = CW * 0.88, size = 14 } = {}) {
  s.addText(t, { x: MX, y, w, h, isTextBox: true, margin: 0, valign: 'top',
    fontFace: F.body, fontSize: size, color: C.text2, lineSpacing: size * 1.5 });
}
function footer(s, n) {
  s.addShape(pres.ShapeType.line, { x: MX, y: 6.88, w: CW, h: 0,
    line: { color: C.line, width: 1 } });
  s.addText(FOOT, { x: MX, y: 6.95, w: 9, h: 0.3, isTextBox: true, margin: 0,
    fontFace: F.body, fontSize: 10, color: C.foot });
  s.addText(String(n), { x: W - MX - 1, y: 6.95, w: 1, h: 0.3, isTextBox: true, margin: 0,
    align: 'right', fontFace: F.body, fontSize: 10, color: C.foot });
}
function card(s, { x, y, w, h, fill = C.surf, line = C.line }) {
  s.addShape(pres.ShapeType.roundRect, { x, y, w, h,
    fill: { color: fill }, line: { color: line, width: 1 }, rectRadius: 0.05 });
}
function tag(s, t, { x, y, w, color = C.text3, size = 9 }) {
  s.addText(t.toUpperCase(), { x, y, w, h: 0.2, isTextBox: true, margin: 0,
    fontFace: F.body, fontSize: size, bold: true, charSpacing: 1.4, color });
}
function chip(s, t, { x, y, w, h = 0.32, fill, color, size = 11, bold = true, line = null }) {
  s.addShape(pres.ShapeType.roundRect, { x, y, w, h, fill: { color: fill },
    line: line ? { color: line, width: 1 } : { color: fill, width: 0 }, rectRadius: 0.5 });
  s.addText(t, { x, y, w, h, isTextBox: true, margin: 0, align: 'center', valign: 'middle',
    fontFace: F.body, fontSize: size, bold, color });
}
function bullet(s, n, { x, y, d = 0.29, fill, color = C.white, size = 11 }) {
  s.addShape(pres.ShapeType.ellipse, { x, y, w: d, h: d,
    fill: { color: fill }, line: { color: fill, width: 0 } });
  s.addText(String(n), { x, y, w: d, h: d, isTextBox: true, margin: 0, align: 'center',
    valign: 'middle', fontFace: F.body, fontSize: size, bold: true, color });
}
// Карточка «заголовок + абзац» — основной строительный блок содержательных слайдов.
function unit(s, { x, y, w, h, over, head, body, fill = C.surf, line = C.line,
                   overColor = C.brand2, headSize = 13.5, bodySize = 11.5, pad = 0.22 }) {
  card(s, { x, y, w, h, fill, line });
  let ty = y + pad;
  if (over) { tag(s, over, { x: x + pad, y: ty, w: w - pad * 2, color: overColor }); ty += 0.27; }
  if (head) {
    s.addText(head, { x: x + pad, y: ty, w: w - pad * 2, h: 0.56, isTextBox: true, margin: 0,
      valign: 'top', fontFace: F.head, fontSize: headSize, bold: true, color: C.text,
      lineSpacing: headSize * 1.18 });
    ty += 0.58;
  }
  if (body) {
    s.addText(body, { x: x + pad, y: ty, w: w - pad * 2, h: y + h - ty - pad * 0.6,
      isTextBox: true, margin: 0, valign: 'top', fontFace: F.body, fontSize: bodySize,
      color: C.text2, lineSpacing: bodySize * 1.42 });
  }
}
// Выделенная полоса с ярлыком слева и текстом справа.
function band(s, { y, h, label, text, fill = C.bg, line = C.ice, labelColor = C.brand2,
                   textColor = C.brand, size = 12.5, labelW = 1.75 }) {
  card(s, { x: MX, y, w: CW, h, fill, line });
  tag(s, label, { x: MX + 0.28, y: y + 0.26, w: labelW, color: labelColor });
  s.addText(text, { x: MX + 0.28 + labelW + 0.22, y: y + 0.2, w: CW - labelW - 0.78,
    h: h - 0.36, isTextBox: true, margin: 0, valign: 'top', fontFace: F.body, fontSize: size,
    color: textColor, lineSpacing: size * 1.45 });
}

