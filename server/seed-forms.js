// Образец формы: опрос о потенциале переиспользования ИИ-решений ДЗМ.
//
// Это не выдуманный пример, а функциональные требования ДЗМ, собранные в
// конструкторе как есть: пять блоков, 24 вопроса, восемь из них условные —
// уточнения о применении и эффектах показываются только тем, кто оценил
// решение на 3 и выше. Ровно та схема, которую в требованиях описали словами
// «настройка в Яндекс Формах: вопросы об эффектах лучше сделать условными».
//
// Одна оговорка о нумерации: в требованиях вопрос 21 назван «Один вариант +
// Длинный текст». В конструкторе это два вопроса — выбор и условное описание
// ограничений, — поэтому дальше нумерация на экране на единицу больше, чем в
// исходном документе. Иначе описание пришлось бы показывать всем, включая тех,
// кто ответил «ограничений нет».
