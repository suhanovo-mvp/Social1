/** Справочник учреждений в виде вариантов ответа. */
function institutionOptions() {
  const rows = q.all(`SELECT short_name, name FROM institutions
                      WHERE kind = 'institution' ORDER BY short_name`);
  const names = rows.length >= 3 ? rows.map((r) => r.name || r.short_name) : FALLBACK_INSTITUTIONS;
  return names.map((label, i) => ({ code: `i${i + 1}`, label }));
}

/** Определение формы в том виде, в каком его принимает конструктор. */
export function aiDzmQuestions() {
  return AI_DZM_FORM.questions.map((qn) => ({
    ...qn,
    options: qn.key === 'q2' ? institutionOptions() : (qn.options ?? []),
  }));
}

/**
 * Заводит образец формы, если его ещё нет. Идемпотентно: форма опознаётся по
 * адресу, и правки, внесённые в неё в конструкторе, при перезапуске не затираются.
 */
export function ensureSampleForms({ demoResponses = true } = {}) {
  if (forms.getFormBySlug(AI_DZM_SLUG)) return null;

  const owner = q.get(`SELECT * FROM users WHERE role IN ('dtszn','pilot_coordinator') AND is_active = 1
                       ORDER BY CASE role WHEN 'dtszn' THEN 0 ELSE 1 END, id LIMIT 1`);
  if (!owner) return null;   // пустая база: форму заведёт первый же запуск после наполнения

  const created = forms.createForm({
    title: AI_DZM_FORM.title, description: AI_DZM_FORM.description, user: owner,
  });
  q.run('UPDATE forms SET slug = ? WHERE id = ?', AI_DZM_SLUG, created.id);

  forms.saveQuestions({ formId: created.id, questions: aiDzmQuestions(), user: owner });
  forms.updateForm({
    formId: created.id, user: owner,
    patch: { access: AI_DZM_FORM.access, closing_text: AI_DZM_FORM.closing_text,
             one_per_user: AI_DZM_FORM.one_per_user, show_progress: AI_DZM_FORM.show_progress },
  });
  forms.publishForm({ formId: created.id, user: owner });

  const form = forms.getFormBySlug(AI_DZM_SLUG);
  if (demoResponses) seedResponses(form);
  // Форма перечитывается: счётчик ответов в ней посчитан до их появления
  return forms.getFormBySlug(AI_DZM_SLUG);
}

