const pick = (list, i) => list[i % list.length];

function seedResponses(form) {
  const questions = forms.questionsOf(form.id);
  const byKey = new Map(questions.map((qn) => [qn.key, qn]));
  const institutions = byKey.get('q2').options;
  // Роль выбирается вместе с участником: без неё проверка прав на заполнение
  // формы не найдёт ни одного права и отклонит все ответы
  const respondents = q.all(`SELECT u.id, u.full_name, u.position, u.institution_id, u.role,
                                    (SELECT group_concat(ur.role_code) FROM user_roles ur
                                     WHERE ur.user_id = u.id) AS extra_roles
                             FROM users u WHERE u.is_active = 1 ORDER BY u.id LIMIT 14`);
  if (respondents.length < 3) return 0;

  const codes = (key, ...idx) => idx.map((i) => byKey.get(key).options[i].code);
  let saved = 0;

  respondents.forEach((user, i) => {
    const rate = (key) => WEIGHTS[key][i % WEIGHTS[key].length];
    const answers = {
      q1: `${user.full_name}, ${user.position || 'специалист'}`,
      q2: { choice: pick(institutions, i).code },
      q3: { choice: codes('q3', i % 4)[0] },
      q4: `oprosy${i + 1}@social1.mos.ru`,
      q5: pick(PAIN_POINTS, i),
      q6: { choices: i % 3 === 0 ? codes('q6', 0, 1) : codes('q6', i % 4) },

      q7: rate('q7'),
      q8: pick(PLACES, i),
      q9: { choices: codes('q9', 0, (i % 2) + 1) },
      q10: { choice: codes('q10', i % 5)[0] },

      q11: rate('q11'),
      q12: { choices: codes('q12', i % 3) },
      q13: { choice: codes('q13', i % 3)[0] },

      q14: rate('q14'),
      q15: { choices: codes('q15', i % 3) },

      q16: rate('q16'),
      q17: { choices: codes('q17', 0, (i % 2) + 1) },

      q18: rate('q18'),
      q19: { choices: codes('q19', i % 3) },

      q20: { choice: codes('q20', i % 3)[0] },
      q21: { choice: ['strict', 'open', 'legal'][i % 3] },
      q21_details: pick(LIMITS, i),
      q22: { choice: codes('q22', i % 3)[0] },
      q23: pick(WISHES, i),
      q24: i % 4 === 0 ? 'Готовы принять коллег из ДЗМ для демонстрации на нашей площадке.' : '',
    };
    try {
      forms.submitResponse({ form, user, answers, source: 'portal' });
      saved += 1;
    } catch (e) {
      console.error(`Образец формы: ответ участника ${user.id} не сохранён — ${e.message}`);
    }
  });
  return saved;
}
