export const scenarioOf = (id) => SCENARIOS.find((s) => s.id === id) || SCENARIOS[0];

export function diagramsForScenario(scenario) {
  return scenario ? DIAGRAMS.filter((d) => d.scenario === scenario) : DIAGRAMS;
}

export function diagramsForRole(role) {
  if (!role || role === 'all') return DIAGRAMS;
  return DIAGRAMS.filter((d) => d.role === role || d.role === 'all');
}

