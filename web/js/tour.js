// roles: '*' — для всех ролей, иначе перечень ролей, которым сценарий полезен.
// perm: право, без которого сценарий не предлагается. Нужен там, где доступ выдают
// конкретному человеку сверх основной роли, — как в каталоге разработчиков.

/**
 * Нажать на элемент, когда раздел его отрисует. Шаг с переходом ждёт только
 * 260 мс, а данные раздела приходят с сервера — без ожидания нажатие уходило бы
 * в пустоту, и тур показывал бы подсказку не к той вкладке.
 */
const clickWhenReady = (selector, timeout = 4000) => {
  const started = Date.now();
  const tick = () => {
    const el = document.querySelector(selector);
    if (el) el.click();
    else if (Date.now() - started < timeout) setTimeout(tick, 80);
  };
  tick();
};

