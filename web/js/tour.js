/** Ожидание появления элемента после перерисовки раздела. */
function waitFor(selector, timeout = 4000) {
  return new Promise((resolve) => {
    if (!selector) return resolve(null);
    const found = document.querySelector(selector);
    if (found) return resolve(found);
    const started = Date.now();
    // Опрос по таймеру, а не по кадрам: в фоновой вкладке браузер приостанавливает
    // requestAnimationFrame, и шаг, ждущий загрузки раздела, остался бы без подсветки
    const tick = () => {
      const el = document.querySelector(selector);
      if (el) return resolve(el);
      if (Date.now() - started > timeout) return resolve(null);
      setTimeout(tick, 60);
    };
    setTimeout(tick, 60);
  });
}

